static float normalize_angle(float angle_deg)
{
    double angle;

    if (!isfinite(angle_deg)) {
        return angle_deg;
    }

    angle = (double)angle_deg;
    angle -= (double)((int64_t)(angle / 360.0)) * 360.0;
    if (angle < 0.0) {
        angle += 360.0;
    }
    return (float)angle;
}

/* Lookup a first-quadrant angle in [0, 90], with linear interpolation. */
static float sin_quarter(float angle_deg)
{
    float table_position = angle_deg * (1000.0f / 90.0f);
    uint16_t index = (uint16_t)table_position;
    float fraction;
    int32_t low;
    int32_t high;

    if (index >= 1000U) {
        return (float)sin_quarter_q15[1000] / 32767.0f;
    }

    fraction = table_position - (float)index;
    low = sin_quarter_q15[index];
    high = sin_quarter_q15[index + 1U];
    return ((float)low + ((float)(high - low) * fraction)) / 32767.0f;
}

float qmath_sin(float angle_deg)
{
    float angle = normalize_angle(angle_deg);

    if (!isfinite(angle)) {
        return angle;
    }

    if (angle <= 90.0f) {
        return sin_quarter(angle);
    }
    if (angle <= 180.0f) {
        return sin_quarter(180.0f - angle);
    }
    if (angle <= 270.0f) {
        return -sin_quarter(angle - 180.0f);
    }
    return -sin_quarter(360.0f - angle);
}

float qmath_cos(float angle_deg)
{
    float angle = normalize_angle(angle_deg);

    if (!isfinite(angle)) {
        return angle;
    }
    angle += 90.0f;
    if (angle >= 360.0f) {
        angle -= 360.0f;
    }
    return qmath_sin(angle);
}

float qmath_tan(float angle_deg)
{
    float cosine = qmath_cos(angle_deg);

    /* Tangent is undefined at odd multiples of 90 degrees. */
    if (cosine > -0.000001f && cosine < 0.000001f) {
        return (qmath_sin(angle_deg) < 0.0f) ? -32767.0f : 32767.0f;
    }
    return qmath_sin(angle_deg) / cosine;
}

float qsin(float angle_deg)
{
    return qmath_sin(angle_deg);
}

float qcos(float angle_deg)
{
    return qmath_cos(angle_deg);
}

float qtan(float angle_deg)
{
    return qmath_tan(angle_deg);
}

/* Return atan2(y, x) in degrees using a ratio lookup and quadrant mapping. */
float qmath_atan2(float y, float x)
{
    float abs_y;
    float abs_x;
    float ratio;
    float position;
    uint16_t index;
    float fraction;
    float acute;
    float angle;

    if (!isfinite(x) || !isfinite(y)) {
        return atan2f(y, x) * (180.0f / 3.14159265358979323846f);
    }
    if (x == 0.0f && y == 0.0f) {
        return 0.0f;
    }

    abs_x = (x < 0.0f) ? -x : x;
    abs_y = (y < 0.0f) ? -y : y;
    if (abs_y <= abs_x) {
        ratio = abs_y / abs_x;
        position = ratio * 1000.0f;
        index = (uint16_t)position;
        if (index >= 1000U) {
            acute = 45.0f;
        } else {
            fraction = position - (float)index;
            acute = ((float)atan_ratio_mdeg[index] +
                     ((float)(atan_ratio_mdeg[index + 1U] - atan_ratio_mdeg[index]) * fraction)) * 0.001f;
        }
    } else {
        ratio = abs_x / abs_y;
        position = ratio * 1000.0f;
        index = (uint16_t)position;
        if (index >= 1000U) {
            acute = 45.0f;
        } else {
            fraction = position - (float)index;
            acute = 90.0f - ((float)atan_ratio_mdeg[index] +
                     ((float)(atan_ratio_mdeg[index + 1U] - atan_ratio_mdeg[index]) * fraction)) * 0.001f;
        }
    }

    if (x >= 0.0f) {
        angle = (y >= 0.0f) ? acute : -acute;
    } else {
        angle = (y >= 0.0f) ? (180.0f - acute) : (acute - 180.0f);
    }
    return angle;
}
